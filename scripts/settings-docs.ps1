$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$source = Get-Content -LiteralPath (Join-Path $projectRoot 'src\SettingsSchema.h') -Raw
$schema = [regex]::Matches($source, '(?s)\{L"([^"]+)",\s*L"([^"]+)",\s*L"([^"]+)",\s*L"([^"]*)",\s*L"([^"]*)",\s*Kind::(\w+)(.*?)\}')
if ($schema.Count -ne 36) { throw "Schema changed: review documentation generator ($($schema.Count) settings)." }
$rows = @('<!-- Generated by scripts/settings-docs.ps1 from src/SettingsSchema.h. -->', '', '| Page | Setting | Default | Bounds / choices | Live preview |', '|---|---|---|---|---|')
foreach ($entry in $schema) {
    $tail = $entry.Groups[7].Value
    $range = [regex]::Match($tail, '^,\s*(-?\d+),\s*(-?\d+)')
    $choices = [regex]::Match($tail, 'L"([^"]+)"')
    $bounds = if ($choices.Success) { $choices.Groups[1].Value.Replace(';', ' / ') } elseif ($entry.Groups[6].Value -eq 'Boolean') { 'Off / On' } elseif ($range.Success -and $entry.Groups[6].Value -eq 'Integer') { $range.Groups[1].Value + '–' + $range.Groups[2].Value } else { 'Validated text (≤1024 characters)' }
    $default = if ($entry.Groups[4].Value -eq '') { '(empty)' } else { $entry.Groups[4].Value }
    $live = if ($tail -match ',\s*true\s*(,\s*(true|false))?\s*$') { 'Yes' } else { 'Apply' }
    $rows += '| ' + $entry.Groups[3].Value + ' | ' + $entry.Groups[2].Value + ' | ' + $default + ' | ' + $bounds + ' | ' + $live + ' |'
}
$path = Join-Path $projectRoot 'docs\SETTINGS.md'
$document = Get-Content -LiteralPath $path -Raw
$start = '<!-- schema:start -->'
$end = '<!-- schema:end -->'
$a = $document.IndexOf($start)
$b = $document.IndexOf($end)
if ($a -lt 0 -or $b -le $a) { throw 'Missing schema documentation markers.' }
$document = $document.Substring(0, $a + $start.Length) + "`n`n" + ($rows -join "`n") + "`n`n" + $document.Substring($b)
[IO.File]::WriteAllText($path, $document, [Text.UTF8Encoding]::new($false))
